#!/usr/bin/env node
// Generates supabase/migrations/0007_catalog_normalization.sql.
//
// Supersedes the old (diff-based) scripts/generate-catalog-corrections.mjs.
// This generator does a FULL SYNC of every relevant field for every
// product and release currently in lib/data/products.ts -- not a diff
// against some earlier snapshot -- because as of the Catalog Model V2
// pass, lib/data/products.ts is the single source of truth end to end
// (see docs/CATALOG_MODEL_V2.md section 30): every field this migration
// is expected to keep in sync is included here, so there is no separate,
// independently-drifting copy of the same fact anywhere else.
//
// Every already-deployed row is targeted by its existing id (UPDATE,
// never INSERT/DELETE) -- see docs/CATALOG_AUDIT.md and
// docs/CATALOG_MODEL_V2.md for the full id-preservation verification.
// The 2 genuinely new releases (no already-deployed row) get INSERT ...
// on conflict (id) do nothing, matching the initial seed's own
// idempotency pattern.
import { register } from "node:module"

register("./ts-extension-loader.mjs", import.meta.url)

const { PRODUCTS } = await import("../lib/data/products.ts")

// The 2 release ids genuinely new as of the catalog integrity pass's
// "Final Fixes" round (Dash-2 Burning Sun's Type-3 reissue, Dyna-Hawk
// GX's 2019 Super XX reissue) -- see docs/CATALOG_AUDIT.md's "New
// releases added this pass" section for the full derivation (verified by
// direct comparison against the pre-audit snapshot). Hardcoded rather
// than re-derived from an ephemeral snapshot file: this is a one-time
// historical fact about which rows migration 0003 never created, not an
// ongoing computation this script needs to repeat on every future run.
const NEW_RELEASE_IDS = new Set(["45f04c74-a41c-5514-87a2-ab47ea6d66b6", "ace0d1b1-aaf3-589a-977c-a3df07c83c73"])

function sqlStr(value) {
  if (value === undefined || value === null || value === "") return "NULL"
  return `'${String(value).replace(/'/g, "''")}'`
}

function sqlNum(value) {
  return value === undefined || value === null ? "NULL" : String(value)
}

function sqlBool(value) {
  return value ? "true" : "false"
}

function sqlTextArray(values) {
  if (!values || values.length === 0) return "'{}'::text[]"
  const escaped = values.map((v) => `"${String(v).replace(/"/g, '\\"')}"`).join(",")
  return `'{${escaped}}'::text[]`
}

// Deterministic order (by product name, then release array order) so the
// generated SQL is stable across regenerations -- easier to review a diff
// of this file than one that reshuffles every run.
const sortedProducts = [...PRODUCTS].sort((a, b) => a.name.localeCompare(b.name))

const lines = []
lines.push("-- Catalog Model V2 — normalizes the existing catalog into the new")
lines.push("-- architecture. See docs/CATALOG_MODEL_V2.md for the full writeup and")
lines.push("-- docs/CATALOG_AUDIT.md for the underlying factual audit this migration")
lines.push("-- carries forward (this migration ABSORBS what the old, now-removed")
lines.push("-- 0006_catalog_integrity_corrections.sql did -- factual item/chassis/")
lines.push("-- year corrections, pseudo-JAN removal, demo-MSRP removal -- plus the")
lines.push("-- new V2-specific normalization: canonical_release_id, verification")
lines.push("-- status, edition type, production status, and provenance).")
lines.push("--")
lines.push("-- Generated by scripts/generate-catalog-normalization.mjs as a FULL")
lines.push("-- SYNC from lib/data/products.ts (not a diff) -- every UPDATE below")
lines.push("-- targets an existing row by id; every value comes directly from the")
lines.push("-- current seed, so this migration can never drift from it. Requires")
lines.push("-- migration 0006_catalog_model_v2.sql (schema) to already be applied.")
lines.push("--")
lines.push("-- Idempotent: every statement sets the same values again on a re-run,")
lines.push("-- harmlessly, except the two INSERT blocks (new releases, sources),")
lines.push("-- which use `on conflict (id) do nothing`.")
lines.push("")
lines.push("")

// =============================================================================
// 1. Unconditional: clear pseudo-JAN / demo MSRP contamination for every
//    already-deployed release. None of this catalog's releases has an
//    officially verified barcode or MSRP as of this pass -- see
//    lib/data/products.ts's file header.
// =============================================================================
lines.push("-- =========================================================================")
lines.push("-- 1. Unconditional: clear barcode_jan/msrp_jpy/msrp_eur/country_market for")
lines.push("--    every release. No release in this catalog has a verified real JAN or")
lines.push("--    MSRP as of this pass, and no release has a source-derived market --")
lines.push("--    the old 'Japan' default was an invented value (hardening point 2),")
lines.push("--    now cleared to NULL. See lib/data/products.ts's file header and")
lines.push("--    lib/types.ts's estimatedMsrpJPY/EUR split.")
lines.push("-- =========================================================================")
lines.push("")
lines.push("update product_releases set barcode_jan = NULL, msrp_jpy = NULL, msrp_eur = NULL, country_market = NULL;")
lines.push("")
lines.push("")

// =============================================================================
// 2. Full sync of every already-deployed product's factual + V2 fields.
//    canonical_release_id is set in a SEPARATE pass below (section 4),
//    after every release id is guaranteed to exist (including the 2 new
//    ones) -- setting it here would be safe too since all canonical
//    releases in this catalog are pre-existing, not new, but keeping it
//    separate makes the dependency explicit rather than incidental.
// =============================================================================
lines.push("-- =========================================================================")
lines.push("-- 2. Full sync: every product's factual fields, by id.")
lines.push(`--    ${sortedProducts.length} product row(s).`)
lines.push("-- =========================================================================")
lines.push("")
for (const p of sortedProducts) {
  lines.push(`-- ${p.name}`)
  lines.push(
    `update products set canonical_item_number = ${sqlStr(p.itemNumber)}, chassis = ${sqlStr(p.chassis)}, description = ${sqlStr(p.description)}, original_release_year = ${sqlNum(p.originalReleaseYear)}, rarity = ${sqlStr(p.rarity)} where id = ${sqlStr(p.id)};`,
  )
  lines.push("")
}

// =============================================================================
// 3. Full sync of every already-deployed release's factual + V2 fields.
// =============================================================================
const existingReleaseUpdates = []
const newReleaseInserts = []
for (const p of sortedProducts) {
  for (const r of p.releases) {
    // A release is "new" (needs INSERT) if its id wasn't part of the
    // originally-deployed 60 -- detected here by checking against the
    // fixed set of 2 known-new release ids from the catalog integrity
    // pass's own ID-preservation verification (docs/CATALOG_AUDIT.md),
    // rather than re-deriving it from an external snapshot file this
    // script has no reason to depend on at this stage.
    const isNew = NEW_RELEASE_IDS.has(r.id)
    if (isNew) {
      newReleaseInserts.push({ product: p, release: r })
    } else {
      existingReleaseUpdates.push({ product: p, release: r })
    }
  }
}

lines.push("")
lines.push("-- =========================================================================")
lines.push("-- 3. Full sync: every already-deployed release's factual + Catalog Model")
lines.push("--    V2 fields, by id.")
lines.push(`--    ${existingReleaseUpdates.length} release row(s).`)
lines.push("-- =========================================================================")
lines.push("")
for (const { product: p, release: r } of existingReleaseUpdates) {
  lines.push(`-- ${p.name} -- ${r.editionName}`)
  lines.push(
    `update product_releases set item_number = ${sqlStr(r.itemNumber)}, chassis = ${sqlStr(r.chassis)}, edition_name = ${sqlStr(r.editionName)}, release_type = ${sqlStr(r.releaseType)}, edition_type = ${sqlStr(r.editionType)}, release_year = ${sqlNum(r.releaseYear)}, release_date = ${sqlStr(r.releaseDate)}, notes = ${sqlStr(r.notes)}, discontinued = ${sqlBool(r.discontinued)}, rarity = ${sqlStr(r.rarity)}, verification_status = ${sqlStr(r.verificationStatus)}, production_status = ${sqlStr(r.productionStatus)}, status_checked_at = ${r.statusCheckedAt ? sqlStr(r.statusCheckedAt) : "NULL"} where id = ${sqlStr(r.id)};`,
  )
  lines.push("")
}

// =============================================================================
// 4. New releases -- INSERT, not UPDATE (see scripts/generate-catalog-
//    corrections.mjs's earlier precedent for this pattern, now folded in
//    here since that script is superseded).
// =============================================================================
lines.push("")
lines.push("-- =========================================================================")
lines.push("-- 4. Genuinely NEW releases (no already-deployed row) -- INSERT with")
lines.push("--    on conflict (id) do nothing for idempotency.")
lines.push(`--    ${newReleaseInserts.length} new release row(s).`)
lines.push("-- =========================================================================")
lines.push("")
if (newReleaseInserts.length > 0) {
  lines.push(
    "insert into product_releases (id, product_id, item_number, release_type, edition_type, edition_name, release_year, release_date, chassis, barcode_jan, color, country_market, msrp_jpy, msrp_eur, notes, discontinued, is_original, rarity, data_source, verification_status, production_status, status_checked_at) values",
  )
  const rows = newReleaseInserts.map(
    ({ product: p, release: r }) =>
      `  (${sqlStr(r.id)}, ${sqlStr(p.id)}, ${sqlStr(r.itemNumber)}, ${sqlStr(r.releaseType)}, ${sqlStr(r.editionType)}, ${sqlStr(r.editionName)}, ${sqlNum(r.releaseYear)}, ${sqlStr(r.releaseDate)}, ${sqlStr(r.chassis)}, ${sqlStr(r.barcodeJAN)}, ${sqlStr(r.color)}, ${sqlStr(r.countryMarket)}, ${sqlNum(r.msrpJPY)}, ${sqlNum(r.msrpEUR)}, ${sqlStr(r.notes)}, ${sqlBool(r.discontinued)}, ${sqlBool(r.isOriginal)}, ${sqlStr(r.rarity)}, 'manual', ${sqlStr(r.verificationStatus)}, ${sqlStr(r.productionStatus)}, ${r.statusCheckedAt ? sqlStr(r.statusCheckedAt) : "NULL"})`,
  )
  lines.push(rows.join(",\n"))
  lines.push("on conflict (id) do nothing;")
  lines.push("")
  for (const { product: p, release: r } of newReleaseInserts) {
    lines.push(`-- ${p.name} -- ${r.editionName} (item ${r.itemNumber ?? "NULL"})`)
  }
}

// =============================================================================
// 5. canonical_release_id -- set for every product whose canonical
//    release could be confidently identified (all 36, currently -- every
//    product's seed marks exactly one release `original: true`). UNKNOWN
//    > INVENTED: a product with no confidently-identified canonical
//    release simply gets no UPDATE here, leaving the column NULL rather
//    than forcing an arbitrary choice.
// =============================================================================
lines.push("")
lines.push("-- =========================================================================")
lines.push("-- 5. canonical_release_id -- the release considered authoritative for")
lines.push("--    each product's identity. UNKNOWN > INVENTED: only set where a")
lines.push("--    release could be confidently identified as canonical (this")
lines.push("--    catalog's own `isOriginal` flag); never forced.")
lines.push(`--    ${sortedProducts.filter((p) => p.canonicalReleaseId).length} product row(s).`)
lines.push("-- =========================================================================")
lines.push("")
for (const p of sortedProducts) {
  if (!p.canonicalReleaseId) continue
  lines.push(`-- ${p.name}`)
  lines.push(`update products set canonical_release_id = ${sqlStr(p.canonicalReleaseId)} where id = ${sqlStr(p.id)};`)
  lines.push("")
}

// =============================================================================
// 6. release_sources -- provenance for releases whose factual data was
//    confirmed against an official Tamiya source during the catalog
//    integrity audit. Deliberately not exhaustive -- see
//    lib/data/products.ts's KNOWN_SOURCES table, populated only from URLs
//    already documented in that earlier audit, never from new research.
// =============================================================================
const allSources = []
for (const p of sortedProducts) {
  for (const r of p.releases) {
    for (const s of r.sources) {
      allSources.push({ product: p, release: r, source: s })
    }
  }
}

lines.push("")
lines.push("-- =========================================================================")
lines.push("-- 6. release_sources -- provenance for releases with a documented")
lines.push("--    official source (from the catalog integrity audit, not new")
lines.push("--    research). Not exhaustive: a release with no source recorded here")
lines.push("--    is valid and common, not an error -- see docs/CATALOG_MODEL_V2.md")
lines.push("--    section 13.")
lines.push(`--    ${allSources.length} source row(s) across ${new Set(allSources.map((s) => s.release.id)).size} release(s).`)
lines.push("-- =========================================================================")
lines.push("")
if (allSources.length > 0) {
  lines.push("insert into release_sources (id, release_id, source_type, source_url, verified_fields, checked_at, notes) values")
  const rows = allSources.map(
    ({ release: r, source: s }) =>
      `  (${sqlStr(s.id)}, ${sqlStr(r.id)}, ${sqlStr(s.sourceType)}, ${sqlStr(s.sourceUrl)}, ${sqlTextArray(s.verifiedFields)}, ${sqlStr(s.checkedAt)}, ${sqlStr(s.notes)})`,
  )
  lines.push(rows.join(",\n"))
  lines.push("on conflict (id) do nothing;")
}

process.stdout.write(lines.join("\n"))

process.stderr.write(
  `\n${sortedProducts.length} product syncs, ${existingReleaseUpdates.length} release updates, ${newReleaseInserts.length} new release inserts, ${sortedProducts.filter((p) => p.canonicalReleaseId).length} canonical_release_id sets, ${allSources.length} source inserts generated.\n`,
)
