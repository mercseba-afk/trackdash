#!/usr/bin/env node
// Generates supabase/migrations/0006_catalog_integrity_corrections.sql by
// diffing the catalog integrity pass's BEFORE snapshot
// (/tmp/products-before.ts, the last-committed lib/data/products.ts prior
// to this pass) against the current (corrected) lib/data/products.ts.
// Diff-based rather than a hand-maintained correction list, specifically
// so the emitted SQL can never drift from what actually changed in the
// source of truth.
//
// Every UPDATE targets a row by its id (unchanged across this whole
// pass -- see docs/CATALOG_AUDIT.md's ID-preservation verification).
// barcode_jan / msrp_jpy / msrp_eur are blanket-cleared for every release
// regardless of diff: none were ever officially verified (see
// lib/data/products.ts's file header, point 2), so none belong in the
// factual DB columns.
import { register } from "node:module"

register("./ts-extension-loader.mjs", import.meta.url)

const { PRODUCTS: AFTER } = await import("../lib/data/products.ts")
const { PRODUCTS: BEFORE } = await import("/tmp/before-check/products.ts")

function sqlStr(value) {
  if (value === undefined || value === null || value === "") return "NULL"
  return `'${String(value).replace(/'/g, "''")}'`
}

const beforeById = new Map()
for (const p of BEFORE) {
  beforeById.set(p.id, p)
  for (const r of p.releases) beforeById.set(r.id, r)
}

const productUpdates = []
const releaseUpdates = []

for (const p of AFTER) {
  const b = beforeById.get(p.id)
  if (!b) continue // shouldn't happen -- every id is stable across this pass
  const sets = []
  if (b.itemNumber !== p.itemNumber) sets.push(`canonical_item_number = ${sqlStr(p.itemNumber)}`)
  if (b.chassis !== p.chassis) sets.push(`chassis = ${sqlStr(p.chassis)}`)
  if (b.description !== p.description) sets.push(`description = ${sqlStr(p.description)}`)
  if (b.originalReleaseYear !== p.originalReleaseYear) sets.push(`original_release_year = ${p.originalReleaseYear}`)
  if (b.rarity !== p.rarity) sets.push(`rarity = ${sqlStr(p.rarity)}`)
  if (sets.length > 0) {
    productUpdates.push({ id: p.id, name: p.name, sets })
  }

  for (const r of p.releases) {
    const rb = beforeById.get(r.id)
    if (!rb) continue
    const rsets = []
    if (rb.itemNumber !== r.itemNumber) rsets.push(`item_number = ${sqlStr(r.itemNumber)}`)
    if (rb.chassis !== r.chassis) rsets.push(`chassis = ${sqlStr(r.chassis)}`)
    if (rb.notes !== r.notes) rsets.push(`notes = ${sqlStr(r.notes)}`)
    if (rb.editionName !== r.editionName) rsets.push(`edition_name = ${sqlStr(r.editionName)}`)
    if (rb.releaseYear !== r.releaseYear) rsets.push(`release_year = ${r.releaseYear}`)
    if (rb.releaseDate !== r.releaseDate) rsets.push(`release_date = ${sqlStr(r.releaseDate)}`)
    if (Boolean(rb.discontinued) !== Boolean(r.discontinued)) rsets.push(`discontinued = ${Boolean(r.discontinued)}`)
    if (rb.rarity !== r.rarity) rsets.push(`rarity = ${sqlStr(r.rarity)}`)
    if (rsets.length > 0) {
      releaseUpdates.push({ id: r.id, edition: r.editionName, sets: rsets })
    }
  }
}

const lines = []
lines.push("-- Catalog integrity pass: corrects already-deployed catalog rows in")
lines.push("-- place, preserving every primary key. See docs/CATALOG_AUDIT.md for")
lines.push("-- the full audit (every product/release, verification status, sources)")
lines.push("-- and lib/data/products.ts's file header + inline comments for the")
lines.push("-- reasoning behind each specific correction below. Generated by")
lines.push("-- scripts/generate-catalog-corrections.mjs (diffed from the pre-audit")
lines.push("-- snapshot -- not hand-written) EXCEPT the schema change and the")
lines.push("-- blanket JAN/MSRP clearing, which are unconditional (see their own")
lines.push("-- comments below) rather than diffed.")
lines.push("--")
lines.push("-- Does NOT touch migrations 0000-0005 or any RLS policy, and does not")
lines.push("-- change any id -- every statement below is a plain UPDATE against an")
lines.push("-- existing row (or one schema-widening ALTER COLUMN), never")
lines.push("-- INSERT/DELETE. Idempotent: re-running this sets the same values")
lines.push("-- again, harmlessly.")
lines.push("")
lines.push("")
lines.push("-- =========================================================================")
lines.push("-- 1. Schema: product_releases.item_number becomes nullable.")
lines.push("--")
lines.push("-- A release whose official Tamiya item number cannot be confidently")
lines.push("-- verified must store NULL, never a placeholder/sentinel string like")
lines.push("-- \"UNVERIFIED\" -- that would itself be fabricated catalog data, exactly")
lines.push("-- what this migration exists to stop doing. products.canonical_item_number")
lines.push("-- is already nullable (migration 0000) and needs no change here.")
lines.push("-- =========================================================================")
lines.push("")
lines.push("alter table product_releases alter column item_number drop not null;")
lines.push("")
lines.push("")
lines.push("-- =========================================================================")
lines.push("-- 2. Unconditional: clear every release's barcode_jan, msrp_jpy, and")
lines.push("--    msrp_eur. None of this catalog's 60 releases has an officially")
lines.push("--    verified value for any of the three -- migration 0003's seed wrote")
lines.push("--    a deterministic PSEUDO-jan (now removed from lib/data/products.ts")
lines.push("--    entirely) and app-level ESTIMATED msrp figures (now clearly renamed")
lines.push("--    estimatedMsrpJPY in the seed source, kept out of the database on")
lines.push("--    purpose) into these factual columns. Both were demo/prototype data,")
lines.push("--    never real historical Tamiya figures -- they don't belong in the")
lines.push("--    database's source of truth. The demo market-pricing engine")
lines.push("--    (lib/data/market.ts, already labeled \"demo\" throughout its own UI)")
lines.push("--    continues to work from the in-app estimatedMsrpJPY figures directly,")
lines.push("--    not from these DB columns.")
lines.push("-- =========================================================================")
lines.push("")
lines.push("update product_releases set barcode_jan = NULL, msrp_jpy = NULL, msrp_eur = NULL;")
lines.push("")
lines.push("")
lines.push("-- =========================================================================")
lines.push("-- 3. Corrected factual fields on already-deployed products, by id.")
lines.push(`--    ${productUpdates.length} product row(s) affected.`)
lines.push("-- =========================================================================")
lines.push("")
for (const u of productUpdates) {
  lines.push(`-- ${u.name}`)
  lines.push(`update products set ${u.sets.join(", ")} where id = ${sqlStr(u.id)};`)
  lines.push("")
}

lines.push("")
lines.push("-- =========================================================================")
lines.push("-- 4. Corrected factual fields on already-deployed releases, by id.")
lines.push(`--    ${releaseUpdates.length} release row(s) affected.`)
lines.push("-- =========================================================================")
lines.push("")
for (const u of releaseUpdates) {
  lines.push(`-- ${u.edition}`)
  lines.push(`update product_releases set ${u.sets.join(", ")} where id = ${sqlStr(u.id)};`)
  lines.push("")
}

process.stdout.write(lines.join("\n"))

process.stderr.write(`\n${productUpdates.length} product update(s), ${releaseUpdates.length} release update(s) generated.\n`)
