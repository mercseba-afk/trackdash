const DICTIONARIES: Record<AppLocale, Messages> = { en: EN, it: IT }

interface I18nContextValue {
  locale: AppLocale
  setLocale: (locale: AppLocale) => void
  t: (key: string, vars?: Vars) => string
}

const I18nContext = React.createContext<I18nContextValue | null>(null)
const STORAGE_KEY = "trackdash.locale"

function translate(locale: AppLocale, key: string, vars?: Vars) {
  let message = DICTIONARIES[locale][key] ?? EN[key] ?? key
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      message = message.replaceAll(`{${name}}`, String(value))
    }
  }
  return message
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const { user } = useStore()
  const [locale, setLocaleState] = React.useState<AppLocale>("en")

  const setLocale = React.useCallback((next: AppLocale) => {
    setLocaleState(next)
    if (typeof window !== "undefined") window.localStorage.setItem(STORAGE_KEY, next)
    if (typeof document !== "undefined") document.documentElement.lang = next
  }, [])

  React.useEffect(() => {
    const stored = window.localStorage.getItem(STORAGE_KEY)
    if (stored === "en" || stored === "it") setLocale(stored)
  }, [setLocale])

  React.useEffect(() => {
    if (!user) return
    let cancelled = false
    getMyProfileAction()
      .then((profile) => {
        if (cancelled) return
        const preferred = profile?.preferredLocale
        if (preferred === "en" || preferred === "it") setLocale(preferred)
      })
      .catch(() => {
        // Local preference remains a safe fallback if account preference fails.
      })
    return () => {
      cancelled = true
    }
  }, [setLocale, user?.id])

  const value = React.useMemo<I18nContextValue>(
    () => ({ locale, setLocale, t: (key, vars) => translate(locale, key, vars) }),
    [locale, setLocale],
  )

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const ctx = React.useContext(I18nContext)
  if (!ctx) throw new Error("useI18n must be used within I18nProvider")
  return ctx
}
